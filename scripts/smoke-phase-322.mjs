import { chromium } from 'playwright';
const browser=await chromium.launch({headless:true,executablePath:process.env.CHROMIUM_PATH||'/usr/local/bin/chromium',args:['--no-sandbox']});
const page=await browser.newPage({viewport:{width:390,height:844}}),errors=[];
page.on('pageerror',e=>errors.push(e.stack||e.message));
page.on('console',m=>{if(m.type()==='error')errors.push(m.text())});
const ok=(v,m)=>{if(!v)throw new Error(m)},today=new Date().toISOString().slice(0,10),availability={};
for(let i=0;i<7;i++)availability[i]={enabled:true,start:'08:00',end:'22:00'};
const state={schemaVersion:7,tab:'timeline',tlView:'today',scheduleDay:today,settings:{todayLimit:10,upcomingDays:7,reviewPopup:false,weekStart:'mon',availability,scheduling:{maxFocus:480,maxSession:120,breakMinutes:15}},goals:[{id:'g1',title:'主目標',kind:'achievement',color:'--blue',status:'active',focus:true,projects:[],tasks:[{id:'t1',title:'整理案例',due:'',estimateMinutes:60,estimate:60,done:false,target:1,count:0,pid:null,mid:null}],routines:[]}],events:[],sessions:[],timeBlocks:[],blockExceptions:[],externalEvents:[],dailyPlans:{},garden:{owned:[],placed:{},collection:[]},rewardTransactions:[],habitScheduleExceptions:[]};
await page.goto(process.env.GHT_URL||'http://127.0.0.1:4173');
await page.evaluate(x=>{localStorage.clear();localStorage.setItem('ght_state_blank',JSON.stringify(x));},state);
await page.reload();
await page.evaluate(()=>openNewSlotDetail('散步',todayMD(),'15:00'));
ok(await page.locator('.directsheet').count()===1,'direct planner sheet missing');
ok(await page.locator('.directtitle').inputValue()==='散步','large direct title missing');
ok(await page.locator('.sheetsection,.sheetlabel,.sheethelp').count()===0,'legacy boxed fields remain');
ok(await page.getByText(/新增時段|編輯.*時段/).count()===0,'legacy sheet heading remains');
const iconStyle=await page.locator('.directicon').first().evaluate(el=>({bg:getComputedStyle(el).backgroundColor,border:getComputedStyle(el).borderStyle}));
ok(iconStyle.bg==='rgba(0, 0, 0, 0)'&&iconStyle.border==='none','top icon is still boxed');
await page.locator('.directsheet').evaluate(el=>el.dataset.identity='keep');
await page.locator('.directrow').filter({hasText:/月.*星期/}).click();
ok(await page.locator('.directcalendar').count()===1,'custom inline calendar did not open');
ok(await page.locator('.directsheet input[type="date"]').count()===0,'native date input still used');
const target=page.locator('.calday:not(.muted):not(.selected)').first();
const targetText=await target.textContent();
await target.click();
ok(await page.locator('.directcalendar').count()===0,'calendar did not collapse after selection');
ok((await page.locator('.directrow').first().textContent()).includes(String(+targetText)),'selected date did not update');
ok(await page.locator('.directsheet').evaluate(el=>el.dataset.identity)==='keep','sheet shell was recreated after date selection');
await page.locator('.directrow').filter({has:page.locator('.timevalue')}).click();
ok(await page.locator('.directtimechoice').count()===2,'start/end switcher missing');
await page.waitForTimeout(120);
await page.evaluate(()=>{const el=document.getElementById('newSlotDirectHour');el.scrollTop=16*38;el.dispatchEvent(new Event('scroll'));});
await page.waitForTimeout(160);
let times=await page.evaluate(()=>directTimes('newSlot'));
ok(times.start==='16:00'&&times.end==='17:00','changing start did not preserve duration');
await page.locator('.directtimechoice').filter({hasText:'結束'}).click();
await page.waitForTimeout(100);
await page.evaluate(()=>{const el=document.getElementById('newSlotDirectMinute');el.scrollTop=6*38;el.dispatchEvent(new Event('scroll'));});
await page.waitForTimeout(160);
times=await page.evaluate(()=>directTimes('newSlot'));
ok(times.start==='16:00'&&times.end==='17:30','end wheel did not update duration in place');
ok(await page.locator('.directsheet').evaluate(el=>el.dataset.identity)==='keep','sheet shell was recreated during time editing');
await page.locator('.directrow').filter({hasText:'不重複'}).click();
await page.getByRole('button',{name:/^每週[日一二三四五六]$/}).click();
ok(await page.locator('.directsheet').evaluate(el=>el.dataset.identity)==='keep','sheet shell was recreated after repeat selection');
ok(await page.getByText(/列表＋滾輪|點按以滾輪調整|右上角.*完成/).count()===0,'helper copy remains');
ok(errors.length===0,`browser errors: ${errors.join(' | ')}`);
console.log('PASS: Phase 3.22 direct planner sheet smoke');
await browser.close();
